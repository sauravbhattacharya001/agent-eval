// The secret scanner, embedded verbatim so init-corpus is self-contained.
const CHECK_SECRETS = String.raw`#!/usr/bin/env node
/**
 * check-secrets.mjs — coarse safety net before committing cases.
 * Exit 0 = no obvious hits. Exit 1 = something looks like a secret/PII.
 * Not a guarantee of cleanliness — still read the diff (see SCRUBBING.md).
 */
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const CASES = join(ROOT, 'cases');

const PATTERNS = [
  ['OpenAI-style key',     /\bsk-[A-Za-z0-9]{20,}\b/],
  ['sk_live / sk_test',    /\bsk_(live|test)_[A-Za-z0-9]{10,}\b/],
  ['AWS access key id',    /\bAKIA[0-9A-Z]{16}\b/],
  ['AWS secret-ish',       /\b(aws_secret_access_key|aws_secret)\b/i],
  ['Google API key',       /\bAIza[0-9A-Za-z_\-]{30,}\b/],
  ['GitHub token',         /\bgh[pousr]_[A-Za-z0-9]{20,}\b/],
  ['Slack token',          /\bxox[baprs]-[A-Za-z0-9-]{10,}\b/],
  ['Bearer token',         /\bBearer\s+[A-Za-z0-9._\-]{20,}/],
  ['Authorization header', /\bAuthorization\b\s*[:=]/i],
  ['Generic secret=***',   /\b(api[_-]?key|apikey|access[_-]?token|secret)\b\s*[:=]\s*["']?[A-Za-z0-9._\-]{12,}/i],
  ['Private key block',    /-----BEGIN (RSA |EC )?PRIVATE KEY-----/],
  ['JWT',                  /\beyJ[A-Za-z0-9_\-]{10,}\.[A-Za-z0-9_\-]{10,}\.[A-Za-z0-9_\-]{10,}\b/],
  ['Email (PII)',          /\b[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}\b/],
  ['Phone (PII)',          /\b\+?\d[\d\s().\-]{9,}\d\b/],
  ['Connection string',    /\b(mongodb|postgres(ql)?|mysql|redis|amqp):\/\/[^\s"']+/i],
];
const ALLOW = [/<REDACTED[_A-Z]*>/, /example\.com/];

function walk(dir) {
  let out = [];
  let entries;
  try { entries = readdirSync(dir); } catch { return out; }
  for (const e of entries) {
    const p = join(dir, e);
    const st = statSync(p);
    if (st.isDirectory()) out = out.concat(walk(p));
    else if (/\.(mjs|js|ts|json|md)$/.test(e)) out.push(p);
  }
  return out;
}

const files = walk(CASES);
if (files.length === 0) { console.log('check-secrets: no case files yet. OK.'); process.exit(0); }

let hits = 0;
for (const f of files) {
  const lines = readFileSync(f, 'utf8').split(/\r?\n/);
  lines.forEach((line, i) => {
    if (ALLOW.some((a) => a.test(line))) return;
    for (const [name, re] of PATTERNS) {
      const m = line.match(re);
      if (m) {
        hits++;
        const s = m[0].length > 40 ? m[0].slice(0, 37) + '...' : m[0];
        console.error('  x [' + name + '] ' + f + ':' + (i + 1) + '  ->  ' + s);
      }
    }
  });
}
if (hits > 0) {
  console.error('\ncheck-secrets: ' + hits + ' possible secret/PII hit(s). SCRUB before committing (see SCRUBBING.md).');
  process.exit(1);
}
console.log('check-secrets: scanned ' + files.length + ' file(s), no obvious secrets/PII. OK (still read the diff).');
process.exit(0);
`;

const EVAL_GATE_WORKFLOW = `# Regression gate: replay the corpus on every push/PR.
# A promoted failure that hasn't been fixed will fail this job and block the merge.
name: eval-gate

on:
  push:
    branches: [main, master]
  pull_request:

jobs:
  corpus-gate:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4

      # Secret hygiene: never let an unscrubbed case reach the branch.
      - name: check-secrets
        run: node scripts/check-secrets.mjs

      # Replay every promoted regression case against the (fixed) agent.
      # Cases run offline via LocalProvider by default; swap providers to gate a
      # live agent. Exit non-zero (any red) fails the job.
      - name: run corpus
        run: npx --yes agent-eval run ./cases/
`;

/** All files init-corpus writes, relative to the target corpus dir. */
export function corpusScaffold(): ScaffoldFile[] {
  return [
    { path: 'README.md', content: README },
    { path: 'SCRUBBING.md', content: SCRUBBING },
    { path: '.gitignore', content: GITIGNORE },
    { path: 'cases/README.md', content: CASES_README },
    { path: 'cases/.gitkeep', content: '' },
    { path: 'raw/.gitkeep', content: '# raw traces stage here and are NEVER committed. See ../SCRUBBING.md\n' },
    { path: 'scripts/check-secrets.mjs', content: CHECK_SECRETS },
    { path: '.github/workflows/eval-gate.yml', content: EVAL_GATE_WORKFLOW },
  ];
}
