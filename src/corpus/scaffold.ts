/**
 * Corpus scaffold — the single source of truth for a private regression corpus.
 *
 * `agent-eval init-corpus <dir>` writes these files so every client's corpus
 * inherits the same secret-hygiene discipline. This is the productized form of
 * the reference corpus repo: raw traces never get committed, only sanitized
 * cases do, and a coarse scanner fails the commit if an obvious secret slips in.
 */

export interface ScaffoldFile {
  /** Relative path under the corpus dir. */
  path: string;
  /** File contents. */
  content: string;
}

const README = `# Regression corpus (PRIVATE)

Generated by \`agent-eval init-corpus\`. **Keep this repository private.**

This is the half of agent-eval that cannot be forked: a growing library of *your*
real production failures, frozen the moment they broke. The engine (public) grades
runs; this corpus is *what it grades against*. It compounds with your traffic.

## The one rule

> Raw traces are radioactive. They stage in \`raw/\` (gitignored, never committed).
> Only sanitized, promoted cases live in \`cases/\`.

Read \`SCRUBBING.md\` before adding anything. Run \`node scripts/check-secrets.mjs\`
before every commit (it is a coarse net, not a guarantee — still read the diff).

## How cases get here

1. A real run fails; its trace lands in \`raw/\` (never committed).
2. Triage ranks it:  \`agent-eval triage ./raw/export.json --format otlp\`
3. Promote the worst into a runnable case:
   \`agent-eval triage ./raw/export.json --format otlp --promote-top 3 --to ./cases\`
4. **Sanitize** the generated case (see \`SCRUBBING.md\`) — strip real content down
   to the structural failure.
5. \`node scripts/check-secrets.mjs\` passes → commit into \`cases/\`.

## Running the corpus as a gate

\`\`\`bash
# from an agent-eval checkout, or via npx:
agent-eval run ./cases/
\`\`\`

Each case replays a captured incident and is EXPECTED TO FAIL until the agent is
fixed. Point its provider at your fixed agent → green. That failure can never
silently regress again. Wire this into CI (see \`.github/workflows/eval-gate.yml\`).

**License:** all rights reserved. Private IP, not open source.
`;

const SCRUBBING = `# Scrubbing discipline

A corpus mined from real traffic is a magnet for leaked secrets and customer data.
Treat every raw trace as radioactive until proven clean.

## The one rule

> Raw traces never get committed. Only sanitized cases do.

## Remove or replace before a case enters \`cases/\`

- **Credentials** — API keys, tokens, cookies, Authorization headers, connection
  strings, private URLs with tokens.
- **PII** — names, emails, phone numbers, addresses, account/customer IDs.
- **Customer content** — the actual text of a customer prompt or the agent's
  answer when it is sensitive.
- **Internal identifiers** — internal hostnames, buckets, service names, ticket ids.

## Keep (this is the value)

The *structure* of the failure, not the content: the failure kind
(timeout/runaway/errored/abandoned/stalled), the *shape* of the triggering input,
token magnitude, runtime, and the regression assertion.

## Sanitizing a promoted case

The generated \`.eval.mjs\` has \`CAPTURED_INPUT\` / \`CAPTURED_OUTPUT\` constants.
Rewrite them with \`<REDACTED_*>\` placeholders that preserve type but not content:

\`\`\`js
// BEFORE (raw — do not commit)
const CAPTURED_INPUT  = "Scrape https://acme-internal/orders?token=***";
// AFTER (sanitized — safe to commit)
const CAPTURED_INPUT  = "Scrape all 400 product pages under <REDACTED_HOST>";
\`\`\`

The assertion (did it return an answer? under the token ceiling?) still holds —
it tests structure, not the sensitive string.

## Before every commit

\`\`\`bash
node scripts/check-secrets.mjs   # coarse scan; must pass. Still read the diff.
\`\`\`

## If a secret ever lands in history

Rotate the credential immediately (assume compromised), scrub history
(\`git filter-repo\` / BFG), force-push. Private is not safe once a real key is committed.
`;

